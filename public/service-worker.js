// Service Worker Cleaner para Vocalis
// Limpa caches e cancela o registro para evitar tela branca em iframes e ambientes de desenvolvimento
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.claim())
  );
});
